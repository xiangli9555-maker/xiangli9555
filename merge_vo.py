SFX_BGM = re.compile(r'音效|bgm音乐|【bgm|BGM', re.I)

def norm(t):
    """安全取 8 元组（id, rel, type, status, name, owner, creator, parent_id）"""
    if len(t) == 8:
        return t
    if len(t) == 9 and t[5] == '':
        return t[:5] + t[6:]
    raise ValueError(f'Unexpected tuple length {len(t)}: {t[:3]}...')

def is_vo(s):
    t = norm(s)
    return (t[2] == '音频'
            and t[3] != 'suspended'
            and not SFX_BGM.search(t[4]))

PLATFORM = re.compile(r'^【(手游\|?PC(?:\|主机)?|PC\|主机|手游\|PC\|主机)】')
SPLIT_LEAD = re.compile(r'^【((?:语音|台词|选角)[-.·]?(?:英|中|英En|中En)?|Vo[.\s]?(?:语音|台词)[-.·]?(?:英|中)?)】|【VO】')
SPLIT_TRAIL = re.compile(r'\s*-\s*【[^】]*$')
NOISE = re.compile(r'【已变更[^】]*】?|【MA\d+】|【YANG\d+】')

def base_name(name):
    n = PLATFORM.sub('', name)
    n = SPLIT_LEAD.sub('', n)
    n = SPLIT_TRAIL.sub('', n)
    n = NOISE.sub('', n)
    return n.strip(' -—–') or name

def area_of(name):
    if '【兵种】' in name: return '干员'
    if '【SOL】' in name or '【玩法：SOL】' in name: return 'SOL'
    if '【系统】' in name: return '系统'
    if '大战场' in name: return '大战场'
    return 'SOL'

def split_role(name):
    m = re.search(r'【(语音|台词|选角)[-.·]?(英|中|英En|中En)?】', name)
    if m: return (m.group(1), m.group(2))
    mv = re.search(r'【Vo\.语音-(英|中)】', name)
    if mv: return ('语音', mv.group(1))
    return (None, None)

